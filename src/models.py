from pydantic import BaseModel, Field
from typing import List
import uuid


class MinimalSource(BaseModel):
    """
    A location of text inside a file of the corpus

    attributes:
        file_path (str): path to the source file, written exactly as in
            the corpus (e.g. data/raw/vllm-0.10.1/docs/features/lora.md)
        first_character_index (int): index of the first character of the
            span in the file
        last_character_index (int): index of the last character of the
            span in the file
    """

    file_path: str
    first_character_index: int
    last_character_index: int


class UnansweredQuestion(BaseModel):
    """
    A question with no answer or sources attached

    attributes:
        question_id (str): unique id of the question, a random uuid4
            is generated if none is given
        question (str): the question text
    """

    question_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    question: str


class AnsweredQuestion(UnansweredQuestion):
    """
    A question with its reference answer and the sources that support it

    attributes:
        sources (List[MinimalSource]): locations in the corpus where the
            answer can be found
        answer (str): the reference answer
    """

    sources: List[MinimalSource]
    answer: str


class RagDataset(BaseModel):
    """
    A dataset of questions, answered or not

    attributes:
        rag_questions (List[AnsweredQuestion | UnansweredQuestion]): the
            questions of the dataset
    """

    rag_questions: List[AnsweredQuestion | UnansweredQuestion]


class MinimalSearchResults(BaseModel):
    """
    The sources retrieved for a single question

    attributes:
        question_id (str): id of the question that was searched
        question (str): the question text
        retrieved_sources (List[MinimalSource]): the retrieved sources,
            ranked from most to least relevant
    """

    question_id: str
    question: str
    retrieved_sources: List[MinimalSource]


class MinimalAnswer(MinimalSearchResults):
    """
    The sources retrieved for a single question and the generated answer

    attributes:
        answer (str): answer generated by the model from the retrieved
            sources
    """

    answer: str


class StudentSearchResults(BaseModel):
    """
    Output of a search over a whole dataset

    attributes:
        search_results (List[MinimalSearchResults]): the search results of
            every question in the dataset
        k (int): number of sources requested per question
    """

    search_results: List[MinimalSearchResults]
    k: int


class StudentSearchResultsAndAnswer(BaseModel):
    """
    Output of answer generation over a whole dataset

    attributes:
        search_results (List[MinimalAnswer]): the search results and the
            generated answer of every question in the dataset
        k (int): number of sources requested per question
    """

    search_results: List[MinimalAnswer]
    k: int
